DEFAULT_CHECK = {"transition_depth": 3, "random_traces": 200, "random_seed": 0, "search_depth": 8}
DEFAULT_AGENT = {"model": None, "effort": None, "budget_usd": 5.0, "repair_rounds": 2}


def namespace_for(app: str) -> str:
    """A Lean namespace for an app name: `dynamic_config-api` -> `DynamicConfigApi`."""
    words = [w for w in re.split(r"[^A-Za-z0-9]+", app) if w]
    ns = "".join(w[:1].upper() + w[1:] for w in words) or "App"
    if ns[0].isdigit() or ns in ("Companion", "Ledger", "Main", "ModelMain", "Lean", "Std"):
        ns = "App" + ns
    return ns


def create(ws: Path, program: Path, app: str | None = None, namespace: str | None = None,
           check: dict | None = None, agent: dict | None = None, sources: list | None = None) -> Config:
    """A new workspace for `program`, with no model yet."""
    ws, program = Path(ws).resolve(), Path(program).resolve()
    if (ws / "companion.json").exists():
        raise FileExistsError(f"{ws} already holds a workspace")
    app = app or program.stem
    config = {"app": app, "workspace": True, "namespace": namespace or namespace_for(app),
              "program": os.path.relpath(program, ws), "check": {**DEFAULT_CHECK, **(check or {})},
              "agent": {**DEFAULT_AGENT, **(agent or {})}}
    if sources:
        config["sources"] = sources
    (ws / "lean").mkdir(parents=True, exist_ok=True)
    (ws / "companion.json").write_text(json.dumps(config, indent=1) + "\n")
    cfg = Config.load(ws)
    refresh(cfg)
    Ledger(cfg.ledger_path).save()
    return cfg


def refresh(cfg: Config) -> None:
    """Write the workspace's generated files, and bring its copy of the generic core up to
    date. Cheap; run before every build."""
    ws, lean, ns = cfg.workspace, cfg.lean_dir, cfg.namespace
    _write_if_changed(lean / "lakefile.toml", LAKEFILE.format(ns=ns))
    _write_if_changed(lean / "lean-toolchain", (REPO / "lean" / "lean-toolchain").read_text())
    for f in CORE.glob("*.lean"):
        _write_if_changed(lean / "Companion" / f.name, f.read_text())
    _write_if_changed(lean / "Main.lean", MAIN.format(ns=ns))
    _write_if_changed(lean / "ModelMain.lean", MODEL_MAIN.format(ns=ns))
    _write_if_changed(ws / "validate.py", VALIDATE.format(repo=str(REPO)))
    _write_if_changed(ws / ".gitignore", "lean/.lake/\nstate/\n")
    if not cfg.ledger_file.exists():
        cfg.ledger_file.write_text(render(Ledger(cfg.ledger_path), cfg.lean_header, cfg.lean_footer,
                                          cfg.property_type)[0])
    cfg.state_dir.mkdir(parents=True, exist_ok=True)


def has_model(cfg: Config) -> bool:
    return (cfg.lean_dir / f"{cfg.namespace}.lean").exists() and (cfg.workspace / "adapter.py").exists()


def model_files(cfg: Config) -> list:
    """The files the LLM writes: the model's Lean modules and the adapter."""
    return [*cfg.vocabulary_files(), cfg.workspace / "adapter.py"]


def save_model(cfg: Config) -> dict:
    """The model's files, to put back with `restore_model` (path -> text)."""
    return {str(p): p.read_text() for p in model_files(cfg) if p.exists()}


def restore_model(cfg: Config, saved: dict) -> None:
    for p in model_files(cfg):
        if str(p) not in saved:
            p.unlink(missing_ok=True)
    for p, text in saved.items():
        Path(p).parent.mkdir(parents=True, exist_ok=True)
        Path(p).write_text(text)


def seed(cfg: Config, lean_files: dict, root_imports: list, adapter: Path, adapter_class: str) -> None:
    """Start a workspace from an existing model instead of an LLM-written one (to compare the
    two, or to study repair on a known model). `lean_files` maps a module path under the
    namespace's directory (e.g. "Model.lean") to its source file; the root module imports
    `root_imports`. The adapter file is copied, with `Adapter` bound to `adapter_class`."""
    ns_dir = cfg.lean_dir / cfg.namespace
    ns_dir.mkdir(parents=True, exist_ok=True)
    for rel, src in lean_files.items():
        shutil.copy(src, ns_dir / rel)
    (cfg.lean_dir / f"{cfg.namespace}.lean").write_text("".join(f"import {m}\n" for m in root_imports))
    text = Path(adapter).read_text()
    if adapter_class != "Adapter":
        text += f"\n\nAdapter = {adapter_class}\n"
    (cfg.workspace / "adapter.py").write_text(text)


def _write_if_changed(path: Path, text: str) -> None:
    """Writing an unchanged file would make Lake rebuild what depends on it."""
    if not path.exists() or path.read_text() != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def python() -> str:
    """The interpreter the LLM should use to run validate.py."""
    return sys.executable
