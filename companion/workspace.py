"""The companion's workspace for one application: where the LLM-written model and adapter live.

```
WS/
  companion.json        config: app, program, namespace, check and agent settings
  lean/                 Lake project
    Companion/          the generic core (copied from this repository; kept up to date)
    <NS>.lean           the model's root module: defines <NS>.app        (written by the LLM)
    <NS>/...            any further modules of the model                 (written by the LLM)
    Ledger.lean         the ledger's properties                           (generated)
    Main.lean           executable companion-app: the model with the ledger's properties
    ModelMain.lean      executable companion-model: the model alone, for validation while
                        the model is being written or repaired            (generated)
  adapter.py            class Adapter: runs abstract actions on the program (written by the LLM)
  validate.py           trace validation, for the LLM to run              (generated)
  TASK.md               the LLM's current task                            (generated)
  state/                ledger, messages, reports, caches, agent logs
```

The model's contract: in namespace <NS>, types `State`, `Action`, `Out` and `Obs`, and
`app : Companion.App State Action Out Obs` with no properties (the ledger supplies them).
"""

